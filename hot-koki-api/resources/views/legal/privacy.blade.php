    <p>ETS Hot Koki Chaud (« Hot Koki », « nous ») exploite l’application Hot Koki Chaud. Cette politique explique les données traitées pour permettre la commande de repas, la livraison, le paiement et l’assistance au Cameroun.</p>

    <h2>1. Données collectées</h2>
    <p>Nous traitons les informations de compte (nom, prénom, e-mail, téléphone), l’adresse et les coordonnées de livraison, la position lorsque vous l’autorisez, les commandes, avis, messages opérationnels, informations techniques de sécurité et jetons de notification. Pour les paiements, nous conservons uniquement les références, montants, statuts et informations masquées nécessaires au suivi. Hot Koki ne conserve pas votre code secret Mobile Money.</p>

    <h2>2. Utilisation des données</h2>
    <p>Les données servent à créer et sécuriser votre compte, afficher les vendeurs pertinents, traiter les commandes, organiser la livraison, prévenir la fraude, assurer le support, traiter les litiges et envoyer les notifications liées au service.</p>

    <h2>3. Géolocalisation</h2>
    <p>La localisation est facultative. Lorsqu’elle est autorisée, elle sert à déterminer les vendeurs disponibles, estimer la distance et exécuter la livraison. Vous pouvez retirer cette autorisation dans les réglages de votre appareil ; certaines fonctions de livraison pourront alors être limitées.</p>

    <h2>4. Partage nécessaire</h2>
    <p>Les informations strictement nécessaires à l’exécution d’une commande sont communiquées au vendeur affecté. Nous utilisons des prestataires techniques pour l’hébergement, les e-mails, les notifications et le paiement. Les données peuvent aussi être communiquées lorsqu’une obligation légale l’impose.</p>

    <h2>5. Paiements</h2>
    <p>Les paiements Mobile Money sont traités par le prestataire de paiement sélectionné. Les demandes, références et statuts sont vérifiés côté serveur. Le prestataire applique ses propres conditions et règles de confidentialité.</p>

    <h2>6. Conservation et sécurité</h2>
    <p>Nous conservons les données pendant la durée du compte et aussi longtemps que nécessaire pour les commandes, litiges, sécurité et obligations légales ou comptables. Nous appliquons notamment HTTPS, le contrôle d’accès par rôle, des mots de passe hachés, la limitation des requêtes et la journalisation de sécurité.</p>

    <h2>7. Vos droits et suppression de compte</h2>
    <p>Vous pouvez consulter et corriger vos informations depuis l’application. Un client peut demander ou effectuer la suppression de son compte depuis son espace personnel ; certaines données de transaction peuvent être conservées lorsque la loi ou un litige l’exige. Pour toute demande relative à vos données, contactez-nous.</p>

    <h2>8. Avis, signalements et modération</h2>
    <p>Les avis publiés peuvent être visibles par les autres utilisateurs. Lorsqu’un avis est signalé, nous traitons l’identifiant de l’avis, le motif, les précisions éventuellement fournies, l’identité du déclarant, la décision de modération et les informations nécessaires à la sécurité. Ces données servent à prévenir les abus, examiner les signalements, masquer les contenus non conformes et traiter les litiges.</p>

    <h2>9. Mineurs et modifications</h2>
    <p>Le service n’est pas destiné aux personnes qui ne peuvent pas légalement conclure une commande. Cette politique peut évoluer ; une version mise à jour sera publiée sur cette page et, si nécessaire, une nouvelle acceptation sera demandée dans l’application.</p>

